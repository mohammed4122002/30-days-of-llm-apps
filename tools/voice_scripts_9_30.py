def closing(d):
    if d.get('finale'):
        return d['finale']
    return (f"الكود كامل على جيت هَب، والرابط بأول تعليق.\n"
            f"وإنت: {d['cta']}\n"
            f"اكتبلي بالتعليقات، وتابعني،\n"
            f"لأنه بكرة: {d['next']}\n"
            f"(وقفة)\nوتذكّر: من غزة… للعالم.\nيلا، سلام.")


def build(n, d):
    segs = [d['hook'], INTRO.format(ord=ORD[n], extra=d.get('intro_extra', ''))] + d['body'] + ["الخلاصة:\n" + d['golden'], closing(d)]
    out = [HEAD.format(name=ORD[n] if n != 30 else 'الثلاثين (الأخير)')]
    for i, s in enumerate(segs, 1):
        num = ''.join(NUM[int(c) - 1] if c != '0' else '٠' for c in str(i))
        out.append(f"---\n\n## المقطع {num}\n\n{s.strip()}\n")
    out.append("---\n\n## قبل ما تسجّل\n\n" + TIPS.format(extra=''.join(f"- {t}\n" for t in d['tips'])) + "\n")
    out.append("## فكرة التصميم (للمونتاج، مش للقراءة)\n\n" + d['design'].strip() + "\n")
    out.append("## ملاحظات التدقيق (مش للقراءة)\n\n" + '\n'.join(f"- {x}" for x in d['notes']) + "\n")
    return '\n'.join(out)


